def changelog_text(limit=None):
    """纯文本版更新日志，给「关于」窗口用。"""
    rows = CHANGELOG[:limit] if limit else CHANGELOG
    out = []
    for ver, items in rows:
        out.append("v%s" % ver)
        for it in items:
            out.append("  · %s" % it)
        out.append("")
    return "\n".join(out).rstrip()
